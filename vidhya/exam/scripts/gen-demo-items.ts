/**
 * Renders the demo's synthetic items (src/demo/items.src.ts) with the brain's own render module
 * (KaTeX + MathML + sanitiser) into src/demo/items.generated.ts.
 *
 *   npm run gen:demo -w exam          regenerate
 *   npm run gen:demo -w exam -- --check   fail if the committed file is stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderText } from '../../brain/src/render/katex';
import { PRACTICE_SRC, mockSrc, type DemoSrcItem } from '../src/demo/items.src';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../src/demo/items.generated.ts');

const plain = (s: string): string => s.replace(/\$/g, '');
function compile(it: DemoSrcItem) {
  return {
    id: it.id,
    topic: it.topic,
    kind: it.kind,
    marks: it.marks,
    negative: it.negative,
    verification: it.verification,
    stemHtml: renderText(it.stem),
    options: it.options?.map((o, i) => ({ key: 'ABCD'[i]!, html: renderText(o) })),
    key: it.key,
    reason: plain(it.reason),
    reasonHtml: renderText(it.reason),
    natTolerance: it.natTolerance,
  };
}

const body = `/* GENERATED by scripts/gen-demo-items.ts from items.src.ts. Do not edit. Synthetic items for the demo build only. */
export interface DemoItem {
  id: string; topic: string; kind: 'mcq' | 'msq' | 'nat'; marks: 1 | 2; negative: string;
  verification: 'verified' | 'rechecking' | 'withdrawn';
  stemHtml: string; options?: { key: string; html: string }[];
  key: string; reason: string; reasonHtml: string; natTolerance?: number;
}
export const PRACTICE_ITEMS: DemoItem[] = ${JSON.stringify(PRACTICE_SRC.map(compile))};
export const MOCK_ITEMS: DemoItem[] = ${JSON.stringify(mockSrc().map(compile))};
`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) { console.error('items.generated.ts is stale: run npm run gen:demo -w exam'); process.exit(1); }
  console.log('items.generated.ts is up to date');
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote ${path.relative(process.cwd(), out)} (${(body.length / 1024).toFixed(0)} KB)`);
}
